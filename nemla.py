def parse_targets(spec: str, max_hosts: int = 1024) -> list:
    """Turn a target spec into a list of IPv4 address strings.

    Supported: single IP, hostname, CIDR (10.0.0.0/24), full range
    (10.0.0.1-10.0.0.50) and short range (10.0.0.1-50).
    """
    spec = spec.strip()
    if not spec:
        raise ValueError(t("bad_range", spec=spec))

    if "/" in spec:
        net = ipaddress.ip_network(spec, strict=False)
        if net.version != 4:
            raise ValueError(t("ipv6"))
        if net.num_addresses > max_hosts:
            raise ValueError(t("too_many", n=net.num_addresses, limit=max_hosts))
        hosts = list(net.hosts()) or list(net)
        return [str(h) for h in hosts]

    m = re.fullmatch(r"(\d+\.\d+\.\d+\.\d+)-(\d+(?:\.\d+\.\d+\.\d+)?)", spec)
    if m:
        first = ipaddress.ip_address(m.group(1))
        end = m.group(2)
        if "." not in end:  # short form: only the last octet changes
            prefix = m.group(1).rsplit(".", 1)[0]
            last = ipaddress.ip_address(f"{prefix}.{end}")
        else:
            last = ipaddress.ip_address(end)
        if last < first:
            raise ValueError(t("bad_range", spec=spec))
        count = int(last) - int(first) + 1
        if count > max_hosts:
            raise ValueError(t("too_many", n=count, limit=max_hosts))
        return [str(ipaddress.ip_address(int(first) + i)) for i in range(count)]

    try:
        addr = ipaddress.ip_address(spec)
    except ValueError:
        try:  # maybe a hostname
            return [socket.gethostbyname(spec)]
        except OSError:
            raise ValueError(t("cannot_resolve", spec=spec)) from None
    if addr.version != 4:
        raise ValueError(t("ipv6"))
    return [str(addr)]


def parse_ports(spec: str) -> list:
    """Parse '22', '22,80,443' or '1-1000' (and mixes) into sorted ports."""
    ports = set()
    for part in spec.split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            a, b = part.split("-", 1)
            lo, hi = int(a), int(b)
            if lo > hi:
                raise ValueError(f"{part}")
            ports.update(range(lo, hi + 1))
        else:
            ports.add(int(part))
    if not ports:
        raise ValueError("empty port list")
    if min(ports) < 1 or max(ports) > 65535:
        raise ValueError("ports must be between 1 and 65535")
    return sorted(ports)


