_VERSION_RULES = (
    (re.compile(r"SSH-[\d.]+-OpenSSH_([\w.]+)"), "OpenSSH"),
    (re.compile(r"SSH-[\d.]+-dropbear_([\w.]+)", re.I), "Dropbear"),
    (re.compile(r"Server:\s*nginx(?:/([\d.]+))?", re.I), "nginx"),
    (re.compile(r"Server:\s*Apache(?:/([\d.]+))?", re.I), "Apache httpd"),
    (re.compile(r"Server:\s*Microsoft-IIS(?:/([\d.]+))?", re.I), "Microsoft IIS"),
    (re.compile(r"Server:\s*lighttpd(?:/([\d.]+))?", re.I), "lighttpd"),
    (re.compile(r"Server:\s*Jetty\(?([\d.]+)?", re.I), "Jetty"),
    (re.compile(r"Server:\s*Caddy", re.I), "Caddy"),
    (re.compile(r"vsFTPd\s+([\d.]+)", re.I), "vsftpd"),
    (re.compile(r"ProFTPD\s+([\d.]+[a-z]?)", re.I), "ProFTPD"),
    (re.compile(r"Pure-FTPd", re.I), "Pure-FTPd"),
    (re.compile(r"Microsoft FTP Service", re.I), "Microsoft FTP"),
    (re.compile(r"Exim\s+([\d.]+)"), "Exim"),
    (re.compile(r"Sendmail\s+([\d./]+)"), "Sendmail"),
    (re.compile(r"Postfix"), "Postfix"),
    (re.compile(r"Dovecot"), "Dovecot"),
    (re.compile(r"^RFB (\d{3}\.\d{3})"), "VNC (RFB)"),
)

_OS_HINTS = (
    (re.compile(r"Ubuntu", re.I), "Ubuntu Linux"),
    (re.compile(r"Debian|Raspbian", re.I), "Debian Linux"),
    (re.compile(r"CentOS|Red Hat|Fedora", re.I), "Red Hat family Linux"),
    (re.compile(r"FreeBSD", re.I), "FreeBSD"),
    (re.compile(r"OpenBSD", re.I), "OpenBSD"),
    (re.compile(r"Win32|Win64|Windows|Microsoft-IIS|Microsoft FTP", re.I), "Windows"),
)

_OLD_TLS = {"SSLv2", "SSLv3", "TLSv1", "TLSv1.1"}


def parse_banner(text: str):
    """(product, version) recognised in a banner, or (None, None)."""
    for rx, product in _VERSION_RULES:
        m = rx.search(text)
        if m:
            return product, (m.group(1) if rx.groups and m.group(1) else None)
    return None, None


def banner_os_hint(text: str):
    for rx, label in _OS_HINTS:
        if rx.search(text):
            return label
    return None


def _printable(text: str, limit: int) -> str:
    return "".join(ch for ch in text if ch.isprintable())[:limit].strip()


def _mysql_product(raw: bytes):
    """MySQL/MariaDB greet first: 4-byte header, protocol 10, NUL-terminated version."""
    if len(raw) > 6 and raw[4] == 10:
        ver = raw[5:].split(b"\x00", 1)[0].decode("latin-1", "ignore")
        m = re.search(r"(\d+\.\d+\.\d+)", ver)
        if m:
            if "mariadb" in ver.lower():
                maria = re.search(r"(\d+\.\d+\.\d+)-MariaDB", ver, re.I)
                return "MariaDB", (maria or m).group(1)
            return "MySQL", m.group(1)
    return None, None


def _read_some(sock, limit: int = 8192, seconds: float = 1.5) -> bytes:
    data = b""
    end = time.time() + seconds
    while len(data) < limit and time.time() < end:
        try:
            chunk = sock.recv(min(4096, limit - len(data)))
        except OSError:  # timeout, reset, TLS error
            break
        if not chunk:
            break
        data += chunk
    return data


def _parse_http(data: bytes) -> dict:
    head, _, body = data.partition(b"\r\n\r\n")
    lines = head.decode("latin-1", "ignore").split("\r\n")
    m = re.match(r"HTTP/[\d.]+\s+(\d{3})", lines[0]) if lines else None
    if not m:
        return {}
    out = {"status": int(m.group(1))}
    headers = {}
    for line in lines[1:]:
        if ":" in line:
            key, value = line.split(":", 1)
            headers[key.strip().lower()] = value.strip()
    for key, label, limit in (("server", "server", 80), ("x-powered-by", "powered_by", 60),
                              ("location", "location", 120)):
        if headers.get(key):
            out[label] = _printable(headers[key], limit)
    page = body.decode("utf-8", "ignore")
    title = re.search(r"<title[^>]*>(.*?)</title>", page, re.I | re.S)
    if title:
        out["title"] = _printable(" ".join(title.group(1).split()), 80)
    version = re.search(r'"number"\s*:\s*"([\d.]+)"', page)
    if version and '"cluster_name"' in page:
        out["elasticsearch"] = version.group(1)
    return out


def _http_get(sock, host: str) -> dict:
    try:
        sock.sendall(f"GET / HTTP/1.0\r\nHost: {host}\r\nUser-Agent: Nemla\r\n"
                     "Accept: */*\r\nConnection: close\r\n\r\n".encode())
    except OSError:
        return {}
    return _parse_http(_read_some(sock))


def _ask(ip: str, port: int, payload: bytes, timeout: float) -> bytes:
    """Open a fresh connection, send `payload`, return the first reply."""
    try:
        with socket.create_connection((ip, port), timeout=timeout) as s:
            s.settimeout(timeout)
            s.sendall(payload)
            return s.recv(1024)
    except OSError:
        return b""


def _decode_cert(der: bytes):
    """Decode a DER certificate with the standard library (no third-party code)."""
    fd, path = tempfile.mkstemp(suffix=".pem")
    try:
        with os.fdopen(fd, "w") as fh:
            fh.write(ssl.DER_cert_to_PEM_cert(der))
        return ssl._ssl._test_decode_cert(path)  # type: ignore[attr-defined]
    except Exception:  # noqa: BLE001 - private helper, may differ between Pythons
        return None
    finally:
        try:
            os.unlink(path)
        except OSError:
            pass


def _cert_name(name, key: str) -> str:
    for rdn in name or ():
        for k, v in rdn:
            if k == key:
                return v
    return ""


def tls_probe(ip: str, port: int, timeout: float = 1.5, http: bool = False):
    """Handshake with any TLS version the server offers. Returns (tls, extra):
    `tls` has version, cipher, subject, issuer, expiry and self-signed flag;
    `extra` may carry the web page details or the mail greeting."""
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE
    try:  # let old servers show themselves so we can report them
        ctx.minimum_version = ssl.TLSVersion.MINIMUM_SUPPORTED
        ctx.set_ciphers("ALL:@SECLEVEL=0")
    except (AttributeError, ValueError, ssl.SSLError):
        pass
    try:
        with socket.create_connection((ip, port), timeout=timeout) as raw:
            with ctx.wrap_socket(raw) as s:
                s.settimeout(timeout)
                tls = {"version": s.version() or "", "cipher": (s.cipher() or ("",))[0]}
                der = s.getpeercert(binary_form=True)
                extra = {}
                if http:
                    web = _http_get(s, ip)
                    if web:
                        extra["http"] = web
                elif port in (465, 993, 995):
                    s.settimeout(0.8)
                    extra["greeting"] = _clean_banner(_read_some(s, 256, 0.8))
    except (OSError, ssl.SSLError, ValueError):
        return None, {}
    cert = _decode_cert(der) if der else None
    if cert:
        tls["subject"] = _printable(_cert_name(cert.get("subject"), "commonName"), 80)
        tls["issuer"] = _printable(_cert_name(cert.get("issuer"), "organizationName")
                                   or _cert_name(cert.get("issuer"), "commonName"), 80)
        tls["self_signed"] = cert.get("subject") == cert.get("issuer")
        try:
            end = ssl.cert_time_to_seconds(cert["notAfter"])
            tls["not_after"] = time.strftime("%Y-%m-%d", time.gmtime(end))
            tls["days_left"] = int((end - time.time()) // 86400)
        except (KeyError, ValueError):
            pass
        sans = [v for k, v in cert.get("subjectAltName", ()) if k == "DNS"]
        if sans:
            tls["san"] = [_printable(x, 60) for x in sans[:6]]
    return tls, extra


def detect_service(ip: str, port: int, raw: bytes = b"", banner: str = "",
                   timeout: float = 1.0) -> dict:
    """Best-effort product, version, web title and TLS details for one open port.

    Only ordinary identification probes are sent (a web GET, a TLS handshake,
    Redis PING, ...), never anything that logs in or changes state. Any failure
    just means less detail, so a detection bug can never break a scan."""
    info = {}
    try:
        product, version = parse_banner(banner)
        if product is None and raw:
            product, version = _mysql_product(raw)
        web, tls, extra = {}, None, {}
        http_like = port in HTTP_PORTS or port == 9200 or banner.upper().startswith("HTTP/")
        if port in TLS_PORTS:
            tls, extra = tls_probe(ip, port, timeout, http=port in (443, 8443))
        elif http_like:
            with socket.create_connection((ip, port), timeout=timeout) as s:
                s.settimeout(timeout)
                web = _http_get(s, ip)
        elif port == 6379:
            pong = _ask(ip, port, b"PING\r\n", timeout)
            if pong.startswith(b"+PONG"):
                product, info["auth"] = "Redis", "none"
                found = re.search(rb"redis_version:([\d.]+)",
                                  _ask(ip, port, b"INFO server\r\n", timeout))
                version = found.group(1).decode() if found else version
            elif pong.startswith((b"-NOAUTH", b"-DENIED", b"-ERR")):
                product, info["auth"] = "Redis", "required"
        elif port == 11211:
            reply = _ask(ip, port, b"version\r\n", timeout)
            if reply.startswith(b"VERSION "):
                product, info["auth"] = "Memcached", "none"
                version = reply[8:].split()[0].decode("latin-1", "ignore")
        elif port == 5432:
            if _ask(ip, port, struct.pack("!II", 8, 80877103), timeout)[:1] in (b"S", b"N"):
                product = "PostgreSQL"
        elif not banner and port not in COMMON_SERVICE_NAMES:
            tls, extra = tls_probe(ip, port, timeout, http=True)

        web = web or extra.get("http") or {}
        if web.get("elasticsearch"):
            product, version = "Elasticsearch", web["elasticsearch"]
            info["auth"] = "none" if web.get("status") == 200 else "required"
        server = web.get("server", "")
        if product is None and server:
            product, version = parse_banner("Server: " + server)
            if product is None:
                m = re.match(r"([A-Za-z][\w.-]*)(?:/([\w.]+))?", server)
                product, version = (m.group(1), m.group(2)) if m else (None, None)
        if product is None and extra.get("greeting"):
            product, version = parse_banner(extra["greeting"])
        for key in ("status", "title", "location", "powered_by"):
            if web.get(key):
                info[key] = web[key]
        if product:
            info["product"] = product
        if version:
            info["version"] = version
        if tls:
            info["tls"] = tls
        hint = banner_os_hint(f"{banner} {server}")
        if hint:
            info["os_hint"] = hint
    except Exception:  # noqa: BLE001 - detection is optional detail
        pass
    return info


def scan_host_ports(ip: str, ports: list, workers: int = 150,
                    timeout: float = 0.7, grab: bool = True, on_port=None,
                    on_progress=None, cancel=None) -> list:
    """Scan `ports` on one host. Optional hooks: on_port(result) for every open
    port as it is found, on_progress(done, total), and a `cancel` event."""
    found = []
    done = 0
    for _, res in _pool_map(lambda p: scan_port(ip, p, timeout, grab),
                            ports, workers, cancel):
        done += 1
        if res:
            found.append(res)
            if on_port:
                on_port(res)
        if on_progress:
            on_progress(done, len(ports))
    return sorted(found, key=lambda r: r["port"])


