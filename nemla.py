def _e(value) -> str:
    """HTML-escape anything that ends up in the report (banners are attacker-controlled)."""
    return html.escape("" if value is None else str(value), quote=True)


def _product_cell(p: dict) -> str:
    name = " ".join(x for x in (p.get("product"), p.get("version")) if x)
    tls = p.get("tls") or {}
    tls_bits = [tls.get("version"), tls.get("subject"),
                ("-> " + tls["not_after"]) if tls.get("not_after") else None]
    small = " | ".join(x for x in (p.get("title"), " ".join(b for b in tls_bits if b)) if x)
    extra = f"<small>{_e(small)}</small>" if small else ""
    return f'<td class="product">{_e(name or "-")}{extra}</td>'


def _findings_html(host: dict) -> str:
    items = "".join(
        f'<li class="sev-{_e(f["severity"])}"><span class="sev">{_e(t("sev_" + f["severity"]))}</span>'
        f'<span>{_e(finding_text(f))}</span></li>'
        for f in host.get("findings", [])
    )
    return f'<ul class="findings">{items}</ul>' if items else ""


def render_host_card(host: dict) -> str:
    if host["open_ports"]:
        rows = "\n".join(
            f'<tr><td class="port">{_e(p["port"])}</td>'
            f'<td>{_e(p["service"])}</td>'
            f'{_product_cell(p)}'
            f'<td class="banner">{_e(p["banner"] or "-")}</td></tr>'
            for p in host["open_ports"]
        )
        body = (
            '<div class="table-wrap"><table>'
            f'<tr><th>{_e(t("r_port"))}</th><th>{_e(t("r_service"))}</th>'
            f'<th>{_e(t("r_product"))}</th>'
            f'<th>{_e(t("r_banner"))}</th></tr>{rows}</table></div>'
        )
    else:
        body = f'<div class="empty">{_e(t("r_no_ports"))}</div>'
    body += _findings_html(host)
    mac = f"MAC: {_e(host['mac'])}" if host.get("mac") else ""
    return (
        '<div class="host-card"><div class="host-header"><div>'
        f'<span class="host-ip">{_e(host["ip"])}</span>'
        f'<span class="badge up">{_e(t("r_active"))}</span>'
        f'<span class="badge os">{_e(host["os_guess"])}</span>'
        f'</div><div class="host-meta">{mac}</div></div>{body}</div>'
    )


def render_html(meta: dict, hosts: list) -> str:
    cards = "\n".join(render_host_card(h) for h in hosts) or (
        f'<p class="empty">{_e(t("r_no_hosts"))}</p>'
    )
    counts = summarize_findings(hosts)
    values = {
        "LANG": _LANG,
        "DIR": "rtl" if _LANG in RTL_LANGS else "ltr",
        "FINDING_COUNT": str(counts["high"] + counts["medium"] + counts["low"]),
        "WARN": "warn" if counts["high"] else "",
        "L_FINDINGS": _e(t("r_findings")),
        "TITLE": _e(t("r_title")),
        "TARGET": _e(meta["target"]),
        "SCAN_TIME": _e(meta["scan_time"]),
        "DURATION": _e(f"{meta['duration']:.1f}"),
        "HOST_COUNT": str(len(hosts)),
        "OPEN_COUNT": str(sum(len(h["open_ports"]) for h in hosts)),
        "PORTS_SCANNED": str(meta["ports_scanned"]),
        "L_TARGET": _e(t("r_target")),
        "L_DATE": _e(t("r_date")),
        "L_DURATION": _e(t("r_duration")),
        "L_HOSTS": _e(t("r_hosts")),
        "L_OPEN": _e(t("r_open")),
        "L_SCANNED": _e(t("r_scanned")),
        "FOOTER": _e(t("r_footer", ver=__version__)),
        "HOST_CARDS": cards,  # already escaped piece by piece
        "MARK": BRAND_MARK.replace("@@ID@@", "a"),  # fixed markup, no scan data
        "MARK_SMALL": BRAND_MARK.replace("@@ID@@", "b"),
    }
    # one pass, so text that came from a scanned host can never be treated as a placeholder
    return re.sub(r"@@([A-Z_]+)@@", lambda m: values.get(m.group(1), m.group(0)), HTML_TEMPLATE)


def json_text(meta: dict, hosts: list) -> str:
    payload = {
        "tool": "nemla", "version": __version__, "target": meta["target"],
        "scan_time": meta["scan_time"],
        "duration_seconds": round(meta["duration"], 2),
        "ports_scanned_per_host": meta["ports_scanned"],
        "findings_summary": meta.get("findings") or summarize_findings(hosts),
        "hosts": hosts,
    }
    return json.dumps(payload, ensure_ascii=False, indent=2)


def csv_text(hosts: list) -> str:
    buf = io.StringIO(newline="")
    w = csv.writer(buf)
    w.writerow(["ip", "mac", "os_guess", "ttl", "port", "service", "banner", "product", "version"])
    for h in hosts:
        base = [h["ip"], h.get("mac") or "", h["os_guess"], h.get("ttl") or ""]
        if not h["open_ports"]:
            w.writerow(base + ["", "", "", "", ""])
        for p in h["open_ports"]:
            w.writerow(base + [p["port"], p["service"], p["banner"],
                               p.get("product", ""), p.get("version", "")])
    return buf.getvalue()


def write_json(path: str, meta: dict, hosts: list) -> None:
    with open(path, "w", encoding="utf-8") as f:
        f.write(json_text(meta, hosts))


def write_csv(path: str, hosts: list) -> None:
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(csv_text(hosts))


