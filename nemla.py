def launch_ui(args) -> int:
    """Start the local 3D interface (needs the nemla_ui/ folder next to this file)."""
    try:
        from nemla_ui import serve
    except ImportError:
        log("The 3D interface files (the nemla_ui/ folder) were not found next to nemla.py.")
        return 1
    return serve(sys.modules[__name__], port=args.ui_port, open_window=not args.no_browser,
                 keep_alive=args.keep_alive, lang=args.lang)


def manage_launcher(args) -> int:
    try:
        from nemla_ui import launcher
    except ImportError:
        log("The 3D interface files (the nemla_ui/ folder) were not found next to nemla.py.")
        return 1
    if args.install_launcher:
        return launcher.install()
    return launcher.uninstall()


def main(argv=None) -> int:
    global _LANG
    parser = build_parser()
    bare = not (sys.argv[1:] if argv is None else list(argv))
    args = parser.parse_args(argv)
    _LANG = args.lang or "en"
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass

    if args.install_launcher or args.uninstall_launcher:
        return manage_launcher(args)
    if args.ui or bare:
        print_banner()
        return launch_ui(args)
    if not args.target:
        parser.error("the following arguments are required: -t/--target "
                     "(or run nemla with no arguments to open the 3D interface)")
    print_banner()

    try:
        ips = parse_targets(args.target, args.max_hosts)
    except ValueError as err:
        log(t("invalid_target", err=err))
        return 1

    try:
        ports = set(parse_ports(args.ports)) if args.ports else set()
    except ValueError as err:
        log(t("invalid_ports", err=err))
        return 1
    if args.top_ports or not ports:
        ports |= set(TOP_PORTS)
    ports = sorted(ports)

    hosts, meta = run_scan(
        args.target, ips, ports, no_ping=args.no_ping, no_os=args.no_os,
        no_banner=args.no_banner, threads=args.threads, timeout=args.timeout,
    )
    if not meta["discovered"]:
        return 0
    log(t("done", sec=meta["duration"]))

    counts = meta["findings"]
    log(t("findings_summary", high=counts["high"], medium=counts["medium"], low=counts["low"]))
    for host in hosts:
        for finding in host["findings"]:
            if finding["severity"] != "info":
                log(f"[{t('sev_' + finding['severity'])}] {host['ip']}: {finding_text(finding)}")

    with open(args.output, "w", encoding="utf-8") as f:
        f.write(render_html(meta, hosts))
    log(t("saved", kind="HTML", path=args.output))
    if args.json:
        write_json(args.json, meta, hosts)
        log(t("saved", kind="JSON", path=args.json))
    if args.csv:
        write_csv(args.csv, hosts)
        log(t("saved", kind="CSV", path=args.csv))
    if args.fail_on:
        hits = sum(n for name, n in counts.items() if SEV_RANK[name] >= SEV_RANK[args.fail_on])
        if hits:
            log(t("fail_on", n=hits, level=t("sev_" + args.fail_on)))
            return 3
    return 0


if __name__ == "__main__":
    sys.exit(main())
