def get_ttl(ip: str):
    if HAVE_SCAPY:
        try:
            pkt = sr1(IP(dst=ip) / ICMP(), timeout=1, verbose=0)
            if pkt is not None:
                return int(pkt.ttl)
        except Exception:  # noqa: BLE001
            pass
    if shutil.which("ping"):
        try:
            out = subprocess.run(
                _ping_cmd(ip), capture_output=True, text=True, timeout=3
            ).stdout
            m = re.search(r"ttl[=:\s]*(\d+)", out, re.IGNORECASE)
            if m:
                return int(m.group(1))
        except (OSError, subprocess.SubprocessError):
            pass
    return None


def guess_os(ttl, open_ports: list) -> str:
    ports = {p["port"] for p in open_ports}
    if 3389 in ports or (445 in ports and 135 in ports):
        return t("os_rdp_smb")
    if ttl is None:
        return t("os_unknown")
    if ttl <= 64:
        base = "Linux / Unix / macOS"
        return t("os_ssh") if 22 in ports else base
    if ttl <= 128:
        return "Windows"
    return "Network device (Cisco/Solaris)"


# ---------------------------------------------------------------------------
# Findings: what a scan result means, in plain words (reporting only)
# ---------------------------------------------------------------------------

SEVERITIES = ("info", "low", "medium", "high")
SEV_RANK = {name: rank for rank, name in enumerate(SEVERITIES)}
_REMOTE_PORTS = {1723, 3389, 5900, 5985, 6000}
_DB_PORTS = {1433, 1521, 3306, 5432, 6379, 9200, 11211, 27017}
_FILE_PORTS = {111, 135, 139, 445, 2049}


def _is_external(ip: str) -> bool:
    """True for addresses on the public internet (exposure is worse there)."""
    try:
        addr = ipaddress.ip_address(ip)
    except ValueError:
        return False
    return not (addr.is_private or addr.is_loopback or addr.is_link_local)


def assess_host(host: dict) -> list:
    """Turn one host's open ports into findings: {id, severity, port, params}.

    Findings are language-neutral; `finding_text()` renders them. This only
    describes what was observed, it never tries to log in or exploit anything.
    """
    external = _is_external(host["ip"])
    found = []

    def add(fid, severity, port=None, **params):
        found.append({"id": fid, "severity": severity, "port": port, "params": params})

    ports = host.get("open_ports", [])
    has_tls = any(p.get("tls") for p in ports)
    plain_web = None
    for p in ports:
        n, service = p["port"], p.get("service", "")
        open_service = p.get("auth") == "none"
        if n == 23:
            add("telnet", "high", n)
        elif n == 21:
            add("ftp", "high" if external else "medium", n)
        elif open_service and n == 6379:
            add("redis_open", "high", n)
        elif open_service and n == 11211:
            add("memcached", "high", n)
        elif open_service and n == 9200:
            add("es_open", "high", n)
        elif n in _REMOTE_PORTS:
            add("remote", "high" if external else "medium", n, service=service)
        elif n in _DB_PORTS:
            add("db", "high" if external else "medium", n, service=service)
        elif n in _FILE_PORTS:
            add("files", "high" if external else "low", n, service=service)
        tls = p.get("tls") or {}
        days = tls.get("days_left")
        if days is not None and days < 0:
            add("tls_expired", "high", n, days=-days)
        elif days is not None and days < 30:
            add("tls_expiring", "medium", n, days=days)
        if tls.get("version") in _OLD_TLS:
            add("tls_old", "medium", n, version=tls["version"])
        if tls.get("self_signed"):
            add("tls_selfsigned", "low", n)
        if p.get("status") and not tls and plain_web is None and n != 9200:
            plain_web = n
        if p.get("product") and p.get("version"):
            add("version", "info", n, product=p["product"], version=p["version"])
    if plain_web is not None and not has_tls:
        add("http_plain", "low", plain_web)
    return sorted(found, key=lambda f: (-SEV_RANK[f["severity"]], f["port"] or 0, f["id"]))


def finding_text(finding: dict) -> str:
    params = dict(finding.get("params") or {})
    params.setdefault("port", finding.get("port"))
    return t("f_" + finding["id"], **params)


def summarize_findings(hosts: list) -> dict:
    counts = {name: 0 for name in SEVERITIES}
    for host in hosts:
        for finding in host.get("findings", []):
            counts[finding["severity"]] += 1
    return counts


