def _is_local(ip: str) -> bool:
    addr = ipaddress.ip_address(ip)
    return addr.is_private and not addr.is_loopback


def arp_scan(ips: list, timeout: int = 2):
    """ARP discovery through scapy. Returns {ip: mac}, or None on failure."""
    if not HAVE_SCAPY:
        return None
    try:
        answered, _ = srp(
            Ether(dst="ff:ff:ff:ff:ff:ff") / ARP(pdst=ips),
            timeout=timeout, retry=1, verbose=0,
        )
    except PermissionError:
        log(t("arp_permission"))
        return None
    except Exception as exc:  # noqa: BLE001
        log(t("arp_failed", err=exc))
        return None
    return {rcv.psrc: rcv.hwsrc for _, rcv in answered}


def tcp_ping(ip: str, ports=DISCOVERY_PORTS, timeout: float = 0.6) -> bool:
    """A host is up if any port accepts the connection or answers with RST."""
    for port in ports:
        try:
            with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
                s.settimeout(timeout)
                if s.connect_ex((ip, port)) in _ALIVE_ERRNOS:
                    return True
        except OSError:
            continue
    return False


def _ping_cmd(ip: str, wait: int = 1) -> list:
    if sys.platform.startswith("win"):
        return ["ping", "-n", "1", "-w", str(wait * 1000), ip]
    if sys.platform == "darwin":  # macOS: -W is in milliseconds
        return ["ping", "-c", "1", "-W", str(wait * 1000), ip]
    return ["ping", "-c", "1", "-W", str(wait), ip]


def icmp_ping(ip: str) -> bool:
    """Ping through the OS `ping` binary (no raw sockets / root needed)."""
    if not shutil.which("ping"):
        return False
    try:
        result = subprocess.run(
            _ping_cmd(ip), stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL, timeout=3,
        )
        return result.returncode == 0
    except (OSError, subprocess.SubprocessError):
        return False


def _pool_map(func, items, workers: int, cancel=None):
    """Run func(item) on a thread pool and yield (item, result) as each one finishes.

    When the optional `cancel` event is set, queued work is dropped and the
    generator stops, so a scan can be interrupted quickly (Ctrl+C or the UI's
    Stop button) instead of draining the whole queue.
    """
    items = list(items)
    if not items:
        return
    ex = ThreadPoolExecutor(max_workers=max(1, min(workers, len(items))))
    futures = {ex.submit(func, item): item for item in items}
    pending = set(futures)
    try:
        while pending:
            if cancel is not None and cancel.is_set():
                return
            done, pending = wait(pending, timeout=0.2, return_when=FIRST_COMPLETED)
            for fut in done:
                yield futures[fut], fut.result()
    finally:
        for fut in pending:
            fut.cancel()
        ex.shutdown(wait=False)


def discover_hosts(ips: list, workers: int = 100, probe_ports=DISCOVERY_PORTS,
                   use_arp: bool = True, on_host=None, on_progress=None,
                   cancel=None) -> dict:
    """ARP first (local networks); if it finds nothing, fall back to ICMP + TCP.

    Optional hooks: on_host(ip, info) for every live host as soon as it is
    known, on_progress(done, total) while sweeping, and a `cancel` event.
    """
    if use_arp and HAVE_SCAPY and ips and all(_is_local(ip) for ip in ips):
        log(t("arp_start", n=len(ips)))
        arp = arp_scan(ips)
        if arp:
            found = {ip: {"mac": mac, "method": "ARP"} for ip, mac in arp.items()}
            for ip, info in found.items():
                if on_host:
                    on_host(ip, info)
            if on_progress:
                on_progress(len(ips), len(ips))
            log(t("found", n=len(found)))
            return found

    log(t("probe_start", n=len(ips)))
    found = {}

    def probe(ip):
        return icmp_ping(ip) or tcp_ping(ip, probe_ports)

    done = 0
    for ip, alive in _pool_map(probe, ips, workers, cancel):
        done += 1
        if alive:
            found[ip] = {"mac": None, "method": "ICMP/TCP"}
            if on_host:
                on_host(ip, found[ip])
        if on_progress:
            on_progress(done, len(ips))
    log(t("found", n=len(found)))
    return found


