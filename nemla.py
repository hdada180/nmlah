def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="nemla",
        description="Nemla (نملة) - lightweight network reconnaissance tool",
        epilog="Only scan systems you own or have explicit permission to test.",
    )
    p.add_argument("-t", "--target", required=True,
                   help="IP, hostname, CIDR (10.0.0.0/24), range (10.0.0.1-50 or 10.0.0.1-10.0.0.50)")
    p.add_argument("-p", "--ports", help="ports: 22 | 22,80,443 | 1-1000")
    p.add_argument("--top-ports", action="store_true",
                   help="scan the common-ports list (default when -p is not given)")
    p.add_argument("-o", "--output", default="nemla_report.html", help="HTML report path")
    p.add_argument("--json", metavar="FILE", help="also write results as JSON")
    p.add_argument("--csv", metavar="FILE", help="also write results as CSV")
    p.add_argument("--no-os", action="store_true", help="skip OS fingerprinting")
    p.add_argument("--no-ping", action="store_true",
                   help="skip host discovery, treat every target as up (like nmap -Pn)")
    p.add_argument("--no-banner", action="store_true", help="skip banner grabbing")
    p.add_argument("--threads", type=int, default=150, help="worker threads (default 150)")
    p.add_argument("--timeout", type=float, default=0.7,
                   help="TCP connect timeout in seconds (default 0.7)")
    p.add_argument("--max-hosts", type=int, default=1024,
                   help="refuse targets larger than this many addresses (default 1024)")
    p.add_argument("--lang", choices=sorted(STRINGS), default="en",
                   help="interface and report language (default en)")
    p.add_argument("--version", action="version", version=f"nemla {__version__}")
    return p


def main(argv=None) -> int:
    global _LANG
    args = build_parser().parse_args(argv)
    _LANG = args.lang
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass
    print_banner()

    try:
        ips = parse_targets(args.target, args.max_hosts)
    except ValueError as err:
        log(t("invalid_target", err=err))
        return 1

    try:
        ports = set(parse_ports(args.ports)) if args.ports else set()
    except ValueError as err:
        log(t("invalid_ports", err=err))
        return 1
    if args.top_ports or not ports:
        ports |= set(TOP_PORTS)
    ports = sorted(ports)
    threads = max(1, args.threads)

    start = time.time()
    if args.no_ping:
        log(t("skip_discovery", n=len(ips)))
        hosts_map = {ip: {"mac": None, "method": "skipped"} for ip in ips}
    else:
        probe_ports = sorted(set(DISCOVERY_PORTS) | set(ports[:15]))
        hosts_map = discover_hosts(ips, workers=threads, probe_ports=probe_ports)
    if not hosts_map:
        log(t("no_hosts"))
        return 0

    log(t("port_count", n=len(ports)))
    hosts = []
    try:
        for ip in sorted(hosts_map, key=lambda x: int(ipaddress.ip_address(x))):
            log(t("scanning", ip=ip))
            open_ports = scan_host_ports(ip, ports, threads, args.timeout,
                                         grab=not args.no_banner)
            ttl = None
            if args.no_os:
                os_guess = t("os_skipped")
            else:
                ttl = get_ttl(ip)
                os_guess = guess_os(ttl, open_ports)
                if ttl:
                    os_guess += f" (TTL={ttl})"
            hosts.append({
                "ip": ip, "mac": hosts_map[ip].get("mac"),
                "discovery": hosts_map[ip].get("method"),
                "os_guess": os_guess, "ttl": ttl, "open_ports": open_ports,
            })
            log(t("host_done", n=len(open_ports), os=os_guess))
    except KeyboardInterrupt:
        log(t("interrupted"))

    meta = {
        "target": args.target,
        "scan_time": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "duration": time.time() - start,
        "ports_scanned": len(ports),
    }
    log(t("done", sec=meta["duration"]))

    with open(args.output, "w", encoding="utf-8") as f:
        f.write(render_html(meta, hosts))
    log(t("saved", kind="HTML", path=args.output))
    if args.json:
        write_json(args.json, meta, hosts)
        log(t("saved", kind="JSON", path=args.json))
    if args.csv:
        write_csv(args.csv, hosts)
        log(t("saved", kind="CSV", path=args.csv))
    return 0


if __name__ == "__main__":
    sys.exit(main())
