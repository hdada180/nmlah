def get_ttl(ip: str):
    if HAVE_SCAPY:
        try:
            pkt = sr1(IP(dst=ip) / ICMP(), timeout=1, verbose=0)
            if pkt is not None:
                return int(pkt.ttl)
        except Exception:  # noqa: BLE001
            pass
    if shutil.which("ping"):
        try:
            out = subprocess.run(
                _ping_cmd(ip), capture_output=True, text=True, timeout=3
            ).stdout
            m = re.search(r"ttl[=:\s]*(\d+)", out, re.IGNORECASE)
            if m:
                return int(m.group(1))
        except (OSError, subprocess.SubprocessError):
            pass
    return None


def guess_os(ttl, open_ports: list) -> str:
    ports = {p["port"] for p in open_ports}
    if 3389 in ports or (445 in ports and 135 in ports):
        return t("os_rdp_smb")
    if ttl is None:
        return t("os_unknown")
    if ttl <= 64:
        base = "Linux / Unix / macOS"
        return t("os_ssh") if 22 in ports else base
    if ttl <= 128:
        return "Windows"
    return "Network device (Cisco/Solaris)"


